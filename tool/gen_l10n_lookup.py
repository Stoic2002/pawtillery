#!/usr/bin/env python3
"""Generates lib/l10n/l10n_lookup.g.dart from app_en.arb.

Config files are pure Dart and refer to player-facing text by ARB key
(`nameKey`). This generates `AppLocalizations.byKey(key)` for every key
without placeholders, so the UI can resolve them without hand-written
switches. Run after editing the ARB files (tool/ci.sh does).
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
arb = json.loads((root / 'lib/l10n/app_en.arb').read_text())
keys = sorted(
    k for k, v in arb.items()
    if not k.startswith('@')
    and not arb.get('@' + k, {}).get('placeholders')
)
lines = [
    '// GENERATED by tool/gen_l10n_lookup.py from app_en.arb. Do not edit.',
    '',
    "import 'app_localizations.dart';",
    '',
    'extension L10nByKey on AppLocalizations {',
    '  /// The string for ARB [key]; throws for unknown keys.',
    '  String byKey(String key) => switch (key) {',
]
lines += [f"        '{k}' => {k}," for k in keys]
lines += [
    "        _ => throw ArgumentError('Unknown l10n key: $key'),",
    '      };',
    '}',
    '',
]
(root / 'lib/l10n/l10n_lookup.g.dart').write_text('\n'.join(lines))
print(f'{len(keys)} keys')
